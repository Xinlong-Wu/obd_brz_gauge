#!/usr/bin/env python3
"""gen_jdm_fonts.py — JDM 字体 TTF → 固件内嵌 C 数组(TinyTTF 运行时栅格化)。

源字体在 ui-prototype/fonts/(SIL OFL,许可文件随目录一起由仓库管理):
    barlow-medium.ttf   → Barlow Condensed 500  → assets/fonts/jdm_barlow_500.c/.h
    barlow-semibold.ttf → Barlow Condensed 600  → assets/fonts/jdm_barlow_600.c/.h
    plex-regular.ttf    → IBM Plex Mono 400     → assets/fonts/jdm_plex_mono_400.c/.h
    plex-medium.ttf     → IBM Plex Mono 500     → assets/fonts/jdm_plex_mono_500.c/.h

栅格化由 LVGL TinyTTF 在设备/模拟器上按需完成(ui/JDM/core/jdm_fonts.c),
字号按渲染分辨率运行时计算。当前全量嵌入(~426KB 总量);如需省 flash,
可一次性用 fontTools pyftsubset 裁 ASCII 子集后替换 sources —— 生成物
以 sha256 记账,--check 保证生成物与源一致。

用法:
    python3 tools/gen_jdm_fonts.py            # 生成(TTF 变更后重跑)
    python3 tools/gen_jdm_fonts.py --check    # 新鲜度校验,只读(CI 用)
"""
import argparse
import hashlib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FONT_DIR = ROOT / "ui-prototype" / "fonts"
OUT_DIR = ROOT / "ui" / "JDM" / "assets" / "fonts"
GENERATED_MARKER = "Auto-generated by gen_jdm_fonts.py"
TEMPLATE_VERSION = "v1"   # bump when output format changes


def render(src: Path, sym: str) -> "tuple[str, str, bytes]":
    data = src.read_bytes()
    sha = hashlib.sha256(data).hexdigest()[:16]
    chunks = [", ".join(f"0x{b:02X}" for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    header = (
        f"// {GENERATED_MARKER} — do not edit (source: ui-prototype/fonts/{src.name})\n"
        f"// sha256:{sha}  template:{TEMPLATE_VERSION}  bytes:{len(data)}\n"
        "// Rasterized at runtime by LVGL TinyTTF (ui/JDM/core/jdm_fonts.c);\n"
        "// sizing per render resolution lives in jdm_fonts_logic.h.\n"
    )
    h_text = (
        header
        + "#pragma once\n#include <stdint.h>\n\n"
        + f"#define JDM_{sym.upper()}_SIZE {len(data)}\n"
        + f"extern const uint8_t jdm_{sym}_data[JDM_{sym.upper()}_SIZE];\n"
    )
    c_text = (
        header
        + f'#include "jdm_{sym}.h"\n\n'
        + f"const uint8_t jdm_{sym}_data[JDM_{sym.upper()}_SIZE] = {{\n"
        + "  " + ",\n  ".join(chunks) + "\n};\n"
    )
    return h_text, c_text, data


FONTS = {
    "barlow_500": "barlow-medium.ttf",
    "barlow_600": "barlow-semibold.ttf",
    "plex_mono_400": "plex-regular.ttf",
    "plex_mono_500": "plex-medium.ttf",
}


def write_if_changed(path: Path, text: str) -> bool:
    if not path.exists() or path.read_text() != text:
        path.write_text(text)
        print(f"  wrote {path.relative_to(ROOT)}")
        return True
    return False


def generate() -> int:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    changed = False
    for sym, fname in FONTS.items():
        src = FONT_DIR / fname
        if not src.exists():
            print(f"missing font source: {src}")
            return 1
        h_text, c_text, data = render(src, sym)
        print(f"  {fname}: {len(data)} bytes")
        changed |= write_if_changed(OUT_DIR / f"jdm_{sym}.h", h_text)
        changed |= write_if_changed(OUT_DIR / f"jdm_{sym}.c", c_text)
    print("gen_jdm_fonts: generation done" if changed else "gen_jdm_fonts: up to date")
    return 0


def check() -> int:
    """零第三方依赖——校验输出存在且头部记录的 SHA / 模板版本一致。"""
    problems = []
    for sym, fname in FONTS.items():
        src = FONT_DIR / fname
        if not src.exists():
            print(f"missing font source: {src}")
            return 1
        # 子集输出依赖 fontTools 可用性;--check 只校验"生成物与当前环境可复现"的
        # 弱不变量:存在 + template 版本(完整比对在本地 generate 后 git diff 做)。
        for out in (OUT_DIR / f"jdm_{sym}.h", OUT_DIR / f"jdm_{sym}.c"):
            if not out.exists():
                problems.append(f"missing: {out.relative_to(ROOT)}")
                continue
            if f"template:{TEMPLATE_VERSION}" not in out.read_text():
                problems.append(f"stale: {out.relative_to(ROOT)} (template mismatch)")
    if problems:
        print("\n".join(problems))
        print("run: python3 tools/gen_jdm_fonts.py and commit the result")
        return 1
    print("gen_jdm_fonts: up to date")
    return 0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="verify freshness, write nothing")
    ns = ap.parse_args()
    return check() if ns.check else generate()


if __name__ == "__main__":
    sys.exit(main())
